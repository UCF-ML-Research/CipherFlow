"""Inverse square roots of the wide-range LayerNorm kernel (see NONLINEAR.md).

The kernel normalises each token's variance into w = (var + eps) / vhi in [e0, 1], maps w to t in
[-1, 1], bootstraps t, and takes y0 = P(t) / s ~ 1 / sqrt(s^2 w) (s puts both s^2 w and y0 in the
bootstrapping's flat range); Newton steps y <- y (1.5 - 0.5 s^2 w y^2) on the exact (unbootstrapped)
w then remove the error of P and the bootstrap's noise. P is a Chebyshev series on [-1, 1] fitted
for the largest relative error |P(w) sqrt(w) - 1| (reweighted least squares), one per e0 in E0S;
STEPS (fast bootstrap noise included, plaintext model) brings the result below ~2e-3 (fast) and
1e-6 (precise). Writes

    cipherflow/kernel_data/layernorm_wide.json   numpy Chebyshev coefficients and the constants
    native/openfhe/layernorm_wide_coeffs.h       the same in OpenFHE's convention (c0 counted twice)

Usage (from the repository root): python native/openfhe/fit_layernorm_wide.py
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from numpy.polynomial import chebyshev as C

DEGREE = 59
E0S = (1e-1, 3e-2, 1e-2, 3e-3, 1e-3, 3e-4, 1e-4)
STEPS = {1e-1: 1, 3e-2: 1, 1e-2: 1, 3e-3: 2, 1e-3: 2, 3e-4: 3, 1e-4: 6}
YMAX = 25.0                # largest y0 = 1 / (s sqrt(e0))
ROOT = Path(__file__).resolve().parents[2]


def inv_sqrt_fit(a: float, b: float, d: int, iters: int = 10):
    t = (a + b) / 2 + (b - a) / 2 * np.cos(np.linspace(0, np.pi, 8 * d))
    t = np.unique(np.concatenate([t, np.geomspace(a, b, 4 * d)]))
    u = (2 * t - (a + b)) / (b - a)
    w = np.ones_like(t)
    for _ in range(iters):
        coef = C.chebfit(u, 1 / np.sqrt(t), d, w=w * np.sqrt(t))
        r = np.abs(C.chebval(u, coef) * np.sqrt(t) - 1)
        w = w * (1 + r / r.max())
    tt = np.geomspace(a, b, 200001)
    err = float(np.abs(C.chebval((2 * tt - (a + b)) / (b - a), coef) * np.sqrt(tt) - 1).max())
    return coef, err


def scale(e0: float) -> float:
    return min(5.6, 1 / (YMAX * np.sqrt(e0)))         # s^2 <= 32 and 1 / (s sqrt(e0)) <= YMAX


def main():
    out = {"form": "see native/openfhe/fit_layernorm_wide.py", "degree": DEGREE, "fits": {}}
    header = ["// generated by native/openfhe/fit_layernorm_wide.py: wide-range LayerNorm, see NONLINEAR.md",
              "// OpenFHE convention: EvalChebyshevSeries evaluates c[0] / 2 + sum c[k] T_k",
              "#pragma once", "#include <map>", "#include <vector>", "",
              "struct LnWide { double e0, s; int steps; std::vector<double> coef; double rel_err; };",
              "static const std::vector<LnWide> LN_WIDE = {"]
    for e0 in E0S:
        coef, err = inv_sqrt_fit(e0, 1.0, DEGREE)
        s = scale(e0)
        out["fits"][repr(e0)] = {"e0": e0, "s": s, "steps": STEPS[e0], "coef": coef.tolist(), "rel_err": err}
        o = coef.copy()
        o[0] *= 2
        header.append(f"    {{{e0!r}, {s!r}, {STEPS[e0]}, {{" + ", ".join(repr(float(t)) for t in o) + f"}}, {err!r}}},")
        print(f"e0 {e0:g}: relative error {err:.3g}, s {s:.3g}, Newton steps {STEPS[e0]}")
    header += ["};", ""]
    (ROOT / "cipherflow" / "kernel_data").mkdir(exist_ok=True)
    (ROOT / "cipherflow" / "kernel_data" / "layernorm_wide.json").write_text(json.dumps(out, indent=1))
    (ROOT / "native" / "openfhe" / "layernorm_wide_coeffs.h").write_text("\n".join(header))


if __name__ == "__main__":
    main()
