"""Inverse polynomials of the wide-range Softmax kernel (see NONLINEAR.md).

    y0 = exp((x - c) / 2^k);  y <- y0 * P1(S0) * AMP^(1/2), S0 = row sum of y0;
    k rounds: s = y^2, S = row sum of s, y = s * inv(S) (* AMP^(1/2) except in the last round)

P1 approximates 1/S on [A1, B1] (rough: its error is the same for every value of a row, so the next
round's normalisation removes it); P2 (degree ROUND_DEGREE) approximates 1/S on [A2, B2] (the rounds'
row sums, which the factor AMP puts in the bootstrapping's flat range): as it is in the middle rounds,
refined by Newton steps in the last. Both are Chebyshev
series in the normalised variable (2 S - (a + b)) / (b - a) in [-1, 1], fitted for the largest
relative error |P(S) S - 1| (reweighted least squares). Writes

    cipherflow/kernel_data/softmax_wide.json   numpy Chebyshev coefficients and the constants
    native/openfhe/softmax_wide_coeffs.h       the same in OpenFHE's convention (c0 counted twice)

Usage (from the repository root): python native/openfhe/fit_softmax_wide.py
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from numpy.polynomial import chebyshev as C

N = 128                  # values per softmax row (tokens per block)
TARGET = 3.0             # k makes (c - smallest row max) / 2^k <= TARGET, so S0 >= exp(-TARGET)
AMP = 32.0               # rows scaled so that y^2 <= AMP: bootstrapped values stay in the flat range
EXP_DEGREE = 13
DEGREE = 59             # P1
ROUND_DEGREE = 27       # P2
ROOT = Path(__file__).resolve().parents[2]


def inv_fit(a: float, b: float, d: int, iters: int = 10):
    """Chebyshev coefficients (numpy convention, variable on [-1, 1]) of P ~ 1/S on [a, b]."""
    t = (a + b) / 2 + (b - a) / 2 * np.cos(np.linspace(0, np.pi, 8 * d))
    t = np.unique(np.concatenate([t, np.geomspace(a, b, 4 * d)]))
    u = (2 * t - (a + b)) / (b - a)
    w = np.ones_like(t)
    for _ in range(iters):
        coef = C.chebfit(u, 1 / t, d, w=w * t)
        r = np.abs(C.chebval(u, coef) * t - 1)
        w = w * (1 + r / r.max())
    tt = np.geomspace(a, b, 200001)
    err = float(np.abs(C.chebval((2 * tt - (a + b)) / (b - a), coef) * tt - 1).max())
    return coef, err


def main():
    a1, b1 = 0.8 * np.exp(-TARGET), 1.2 * N
    c1, e1 = inv_fit(a1, b1, DEGREE)
    # after the first normalisation every row sums to AMP^(1/2) (1 +- e1): sums of squares in
    # AMP (1 +- e1)^2 [1/N, 1]; later rounds are closer to exact
    a2, b2 = 0.9 * AMP * (1 - e1) ** 2 / N, 1.1 * AMP * (1 + e1) ** 2
    c2, e2 = inv_fit(a2, b2, ROUND_DEGREE)
    zeta = 1 / np.sqrt(a2 * b2)          # z = P2 / zeta ~ 1 / (zeta S): z and zeta S both <= AMP
    out = {"form": "see native/openfhe/fit_softmax_wide.py", "n": N, "target": TARGET, "amp": AMP,
           "exp_degree": EXP_DEGREE, "degree": DEGREE, "round_degree": ROUND_DEGREE,
           "first": {"a": a1, "b": b1, "coef": c1.tolist(), "rel_err": e1},
           "rounds": {"a": a2, "b": b2, "coef": c2.tolist(), "rel_err": e2, "zeta": zeta}}
    (ROOT / "cipherflow" / "kernel_data").mkdir(exist_ok=True)
    (ROOT / "cipherflow" / "kernel_data" / "softmax_wide.json").write_text(json.dumps(out, indent=1))
    o1, o2 = c1.copy(), c2.copy()
    o1[0] *= 2
    o2[0] *= 2
    fmt = lambda v: "{" + ", ".join(repr(float(t)) for t in v) + "}"
    header = ["// generated by native/openfhe/fit_softmax_wide.py: wide-range Softmax, see NONLINEAR.md",
              "// OpenFHE convention: EvalChebyshevSeries evaluates c[0] / 2 + sum c[k] T_k",
              "#pragma once", "#include <vector>", "",
              f"static const double SMW_N = {N}, SMW_TARGET = {TARGET!r}, SMW_AMP = {AMP!r};",
              f"static const int SMW_EXP_DEGREE = {EXP_DEGREE};",
              f"static const double SMW_A1 = {a1!r}, SMW_B1 = {b1!r}, SMW_A2 = {a2!r}, SMW_B2 = {b2!r};",
              f"static const double SMW_ZETA = {zeta!r};",
              f"static const std::vector<double> SMW_P1 = {fmt(o1)};",
              f"static const std::vector<double> SMW_P2 = {fmt(o2)};", ""]
    (ROOT / "native" / "openfhe" / "softmax_wide_coeffs.h").write_text("\n".join(header))
    print(f"first: [{a1:.4g}, {b1:g}] relative error {e1:.3g}; rounds: [{a2:.4g}, {b2:.4g}] relative error "
          f"{e2:.3g}, zeta {zeta:.4g}")


if __name__ == "__main__":
    main()
