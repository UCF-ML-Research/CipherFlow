"""Coefficients of the wide-range GeLU kernel (see NONLINEAR.md).

    GeLU(x) = x * h(f1(x / B)),   h(v) = (1 + f2(v)) / 2,   f2(f1(u)) ~ erf(u B / sqrt 2)

f1 (degree D1) and f2 (degree D2) are Chebyshev series on [-1, 1], fitted jointly to minimise the
largest |error| of GeLU on [-B, B] (least squares, reweighted towards minimax), with |f1| <= VMAX so
that f2 is only evaluated inside its domain. Writes

    cipherflow/kernel_data/gelu_wide.json   numpy Chebyshev coefficients (the emulator's source)
    native/openfhe/gelu_wide_coeffs.h       the same in OpenFHE's convention (c0 counted twice)

Usage (from the repository root): python native/openfhe/fit_gelu_wide.py
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from numpy.polynomial import chebyshev as C
from scipy.optimize import least_squares
from scipy.special import erf

D1, D2, VMAX = 59, 27, 0.95
BOUNDS = (32, 64, 128, 256)
ROOT = Path(__file__).resolve().parents[2]


def gelu(x):
    return 0.5 * x * (1 + erf(x / np.sqrt(2)))


def fit(B: float, d1: int = D1, d2: int = D2, iters: int = 6):
    u = np.unique(np.concatenate([np.linspace(-1, 1, 6001), np.linspace(-8 / B, 8 / B, 4001)]))
    x, y = u * B, gelu(u * B)
    best = None
    for s in (1.25, 1.1, 1.05):                       # initial f1 = erf / s, f2 = its inverse (clipped)
        p = np.concatenate([C.chebinterpolate(lambda t: erf(t * B / np.sqrt(2)) / s, d1),
                            C.chebinterpolate(lambda t: np.clip(t * s, -1, 1), d2)])
        w = np.ones_like(u)

        def resid(q):
            v = C.chebval(u, q[:d1 + 1])
            over = np.maximum(np.abs(v) - VMAX, 0) * 1e3
            return np.concatenate([w * (x * (1 + C.chebval(v, q[d1 + 1:])) / 2 - y), over])

        for _ in range(iters):
            p = least_squares(resid, p, method="lm", max_nfev=4000).x
            r = np.abs(resid(p)[:len(u)] / w)
            w = w * (1 + r / r.max()) ** 2
            w /= w.mean()
        err = check(B, p[:d1 + 1], p[d1 + 1:])
        if np.abs(C.chebval(np.linspace(-1, 1, 20001), p[:d1 + 1])).max() <= VMAX + 1e-6 and (
                best is None or err < best[0]):
            best = (err, p[:d1 + 1], p[d1 + 1:])
    return best


def check(B, c1, c2, n=400001):
    x = np.linspace(-B, B, n)
    return float(np.abs(x * (1 + C.chebval(C.chebval(x / B, c1), c2)) / 2 - gelu(x)).max())


def main():
    out = {"form": "GeLU(x) = x * h(f1(x / B)), h = (1 + f2) / 2; numpy Chebyshev series on [-1, 1]",
           "degrees": [D1, D2], "f1_bound": VMAX, "kernels": {}}
    header = ["// generated by native/openfhe/fit_gelu_wide.py: wide-range GeLU, see NONLINEAR.md",
              "// OpenFHE convention: EvalChebyshevSeries evaluates c[0] / 2 + sum c[k] T_k",
              "#pragma once", "#include <map>", "#include <vector>", "",
              "struct GeluWide { std::vector<double> f1, h; double max_err; };",
              "static const std::map<int, GeluWide> GELU_WIDE = {"]
    for B in BOUNDS:
        err, c1, c2 = fit(B)
        h = c2 / 2
        h[0] += 0.5
        out["kernels"][str(B)] = {"bound": B, "f1": c1.tolist(), "h": h.tolist(), "max_err": err}
        o1, oh = c1.copy(), h.copy()
        o1[0] *= 2
        oh[0] *= 2
        fmt = lambda v: "{" + ", ".join(repr(float(t)) for t in v) + "}"
        header.append(f"    {{{B}, {{{fmt(o1)}, {fmt(oh)}, {err!r}}}}},")
        print(f"B = {B}: max |error| {err:.3g} (noise-free)", flush=True)
    header += ["};", ""]
    (ROOT / "cipherflow" / "kernel_data").mkdir(exist_ok=True)
    (ROOT / "cipherflow" / "kernel_data" / "gelu_wide.json").write_text(json.dumps(out, indent=1))
    (ROOT / "native" / "openfhe" / "gelu_wide_coeffs.h").write_text("\n".join(header))


if __name__ == "__main__":
    main()
